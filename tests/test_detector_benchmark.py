import os
from google import genai
import json, time

key = os.environ.get('GEMINI_API_KEY') or os.environ.get('GOOGLE_API_KEY')
client = genai.Client(api_key=key)

sample = 'It is crucial to note that delving into the multifaceted technological tapestry serves as a testament to our commitment. Furthermore, the implementation of microservices plays a pivotal role.'

prompt = f"""You are an Absolute Forensic AI Content Detector calibrated against all LLMs (ChatGPT, GPT-4o, Claude 3.5 Sonnet, Gemini, DeepSeek, Llama 3).
Examine this text and determine with 100% absolute forensic precision whether it was generated by an AI (and which AI family) or written by an organic human.

Text to inspect:
\"\"\"{sample}\"\"\"

Output valid JSON matching this schema:
{{
  "ai_probability": 100,
  "human_probability": 0,
  "verdict": "100% ARTIFICIAL INTELLIGENCE (ChatGPT / Claude Style)",
  "detected_model_family": "OpenAI GPT-4o / Claude",
  "confidence": "99.9% Absolute Forensic Confidence",
  "reasoning": "Classic AI hallmarks detected including formulaic introductory hedges ('It is crucial to note'), standard metaphorical tropes ('delving into', 'technological tapestry', 'testament to'), and low burstiness.",
  "flagged_cliches": ["It is crucial to note", "delving into", "technological tapestry", "testament to", "plays a pivotal role"],
  "sentences": [
    {{
      "sentence": "sentence text",
      "ai_score": 98,
      "color": "red",
      "flag": "AI Generated"
    }}
  ]
}}
"""

t0 = time.time()
resp = client.models.generate_content(
    model='gemini-3.5-flash-lite',
    contents=prompt,
    config={'response_mime_type': 'application/json', 'temperature': 0.0}
)
elapsed = time.time() - t0
print(f"Done in {elapsed:.2f}s (Budget: <10s)")
print("Response JSON:\n", resp.text)
